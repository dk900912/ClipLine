namespace ClipLine.Domain;

/// <summary>剪贴板某一时刻的类型与体量快照；平台层用 OleGetClipboard 填充，门面只消费它。</summary>
public sealed record ClipboardSnapshot(
    IReadOnlyList<string> Types,
    long ByteLength,
    long PixelCount,
    bool Decodable,
    string Hash);

/// <summary>C-03 / C-04 / C-05 / C-06：严格过滤、体量上限、命名与去重。</summary>
public static class ClipboardFilter
{
    public const long MaxBytes = 64L * 1024 * 1024;
    public const long MaxPixels = 80_000_000L;

    /// <summary>0600（仅本人可读），C-05。</summary>
    public const int FileModeOwnerOnly = 0b110000000; // 384

    private static readonly string[] ForbiddenTypes =
    {
        "public.utf8-plain-text", "Text", "UnicodeText",
        "public.file-url", "FileDrop", "FileNameW",
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "ExcludeFromClipboardHistory",
    };

    private static readonly string[] AllowedImageTypes =
    {
        "public.png", "public.tiff", "PNG", "TIFF", "CF_DIB", "CF_DIBV5",
    };

    public static bool ContainsForbiddenType(ClipboardSnapshot snapshot) =>
        snapshot.Types.Any(t => ForbiddenTypes.Any(f => t.Contains(f, StringComparison.OrdinalIgnoreCase)));

    public static bool ContainsImageType(ClipboardSnapshot snapshot) =>
        snapshot.Types.Any(t => AllowedImageTypes.Any(a => t.Contains(a, StringComparison.OrdinalIgnoreCase)));

    public static bool Accept(ClipboardSnapshot snapshot, bool clipboardEnabled, out string reason)
    {
        reason = string.Empty;
        if (!clipboardEnabled) { reason = "监听未开启"; return false; }
        if (ContainsForbiddenType(snapshot)) { reason = "含文本 / 文件引用 / 私密标记"; return false; }
        if (!ContainsImageType(snapshot)) { reason = "不是可接受的图像类型"; return false; }
        if (snapshot.ByteLength > MaxBytes) { reason = "超过 64 MB"; return false; }
        if (snapshot.PixelCount > MaxPixels) { reason = "超过 8000 万像素"; return false; }
        if (!snapshot.Decodable) { reason = "解码失败"; return false; }
        return true;
    }

    /// <summary>C-05：Clipboard yyyy-MM-dd at HH.mm.ss.png，同名追加「 2」「 3」。</summary>
    public static string FileName(DateTime timestamp, int ordinal = 0)
    {
        string name = "Clipboard " + timestamp.ToString("yyyy-MM-dd 'at' HH.mm.ss", System.Globalization.CultureInfo.InvariantCulture);
        if (ordinal > 0) name += " " + (ordinal + 1).ToString(System.Globalization.CultureInfo.InvariantCulture);
        return name + ".png";
    }
}

/// <summary>C-06：与上一次完全相同的图片且文件仍在，则不重复挂；被取下后可再次挂上。</summary>
public sealed class ClipboardDedupe
{
    private string? _lastHash;
    private string? _lastPath;

    public bool IsDuplicate(string hash, Func<string, bool> fileStillExists)
    {
        if (_lastHash is null || !string.Equals(_lastHash, hash, StringComparison.Ordinal)) return false;
        return _lastPath is not null && fileStillExists(_lastPath);
    }

    public void Remember(string hash, string path)
    {
        _lastHash = hash;
        _lastPath = path;
    }

    /// <summary>卡片被取下后允许同一张图再次挂上。</summary>
    public void Forget() => _lastPath = null;
}
